function mapDaysFromLabel(label) {
  if (label === "9.30") return [0];
  const match = label.match(/^10\.(\d)(?:–(\d))?/);
  if (!match) return [];
  const start = Number(match[1]);
  const end = Number(match[2] || match[1]);
  return Array.from({ length: end - start + 1 }, (_, index) => start + index);
}

