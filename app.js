function setupCardSliders(parent) {
  if (!parent) return;
  parent.querySelectorAll("[data-card-slider]").forEach(slider => {
    const slides = slider.querySelectorAll(".card-slide");
    const countEl = slider.querySelector("[data-slider-count]");
    const dots = slider.querySelectorAll("[data-slider-dot]");
    const prev = slider.querySelector("[data-slider-prev]");
    const next = slider.querySelector("[data-slider-next]");
    if (slides.length <= 1) return;

    let index = 0;

    function update(newIdx) {
      slides[index].classList.remove("active");
      if (dots[index]) dots[index].classList.remove("active");
      index = (newIdx + slides.length) % slides.length;
      slides[index].classList.add("active");
      if (dots[index]) dots[index].classList.add("active");
      if (countEl) countEl.textContent = `${index + 1} / ${slides.length}`;
    }

    prev?.addEventListener("click", (e) => { e.stopPropagation(); update(index - 1); });
    next?.addEventListener("click", (e) => { e.stopPropagation(); update(index + 1); });
    dots.forEach(dot => {
      dot.addEventListener("click", (e) => {
        e.stopPropagation();
        update(Number(dot.dataset.sliderDot));
      });
    });
  });
}

function setupHeroCarousel() {
  const container = document.querySelector("[data-hero-carousel]");
  if (!container) return;
  const slides = container.querySelectorAll(".hero-slide");
  const dotsContainer = container.querySelector("[data-hero-dots]");
  const prevBtn = container.querySelector("[data-hero-prev]");
  const nextBtn = container.querySelector("[data-hero-next]");
  if (!slides.length) return;

  let current = 0;
  let timer = null;

  dotsContainer.innerHTML = Array.from(slides).map((_, i) => 
    `<button type="button" class="hero-dot ${i === 0 ? "active" : ""}" data-hero-dot="${i}" aria-label="切换到第 ${i + 1} 张封面"></button>`
  ).join("");

  const dots = dotsContainer.querySelectorAll("[data-hero-dot]");

  function goTo(index) {
    slides[current].classList.remove("active");
    if (dots[current]) dots[current].classList.remove("active");
    current = (index + slides.length) % slides.length;
    slides[current].classList.add("active");
    if (dots[current]) dots[current].classList.add("active");
  }

  function next() { goTo(current + 1); }
  function prev() { goTo(current - 1); }

  function resetTimer() {
    if (timer) clearInterval(timer);
    timer = setInterval(next, 4000);
  }

  prevBtn?.addEventListener("click", () => { prev(); resetTimer(); });
  nextBtn?.addEventListener("click", () => { next(); resetTimer(); });

  dots.forEach(dot => {
    dot.addEventListener("click", () => {
      goTo(Number(dot.dataset.heroDot));
      resetTimer();
    });
  });

  let touchStartX = 0;
  container.addEventListener("touchstart", (e) => { touchStartX = e.changedTouches[0].screenX; }, { passive: true });
  container.addEventListener("touchend", (e) => {
    const diff = e.changedTouches[0].screenX - touchStartX;
    if (Math.abs(diff) > 40) {
      if (diff > 0) prev();
      else next();
      resetTimer();
    }
  }, { passive: true });

  resetTimer();
}

function setupLightbox() {
  const lightbox = document.querySelector("[data-lightbox]");
  if (!lightbox) return;
  const imgEl = lightbox.querySelector("[data-lightbox-img]");
  const capEl = lightbox.querySelector("[data-lightbox-caption]");
  const closeBtn = lightbox.querySelector("[data-lightbox-close]");

  function open(src, caption) {
    imgEl.src = src;
    imgEl.alt = caption || "图片预览";
    capEl.textContent = caption || "";
    lightbox.classList.add("active");
    lightbox.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  }

  function close() {
    lightbox.classList.remove("active");
    lightbox.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
    imgEl.src = "";
  }

  document.addEventListener("click", (e) => {
    const target = e.target.closest("[data-lightbox-trigger]");
    if (target) {
      e.preventDefault();
      const img = target.tagName === "IMG" ? target : target.querySelector("img");
      const src = img ? img.src : (target.src || target.dataset.src);
      const caption = target.dataset.caption || img?.alt || target.alt || "";
      if (src) open(src, caption);
    }
  });

  closeBtn?.addEventListener("click", close);
  lightbox.addEventListener("click", (e) => {
    if (e.target === lightbox || e.target.classList.contains("lightbox-content")) close();
  });
  window.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && lightbox.classList.contains("active")) close();
  });
}

